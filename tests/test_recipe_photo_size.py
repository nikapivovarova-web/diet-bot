@pytest.mark.parametrize("basename", CONVERTED_PHOTO_BASENAMES)
def test_converted_photo_is_small_jpeg(basename):
    jpg = PHOTO_DIR / f"{basename}.jpg"
    assert jpg.exists(), f"expected converted JPEG missing: {jpg.name}"
    assert not (PHOTO_DIR / f"{basename}.png").exists(), (
        f"PNG reappeared for {basename}; catalog should stay JPEG"
    )
    size = jpg.stat().st_size
    assert size <= MAX_BYTES, (
        f"{jpg.name} is {size} bytes (> {MAX_BYTES}); recompress it"
    )


def test_converted_set_complete():
    assert len(CONVERTED_PHOTO_BASENAMES) == 218
