def main() -> None:
    with tempfile.TemporaryDirectory(prefix="recipes_notes_") as tmp_name:
        tmp = Path(tmp_name)
        with zipfile.ZipFile(INPUT, "r") as zf:
            zf.extractall(tmp)

        shared_path = tmp / "xl" / "sharedStrings.xml"
        sheet_path = tmp / "xl" / "worksheets" / "sheet1.xml"
        shared_tree = ET.parse(shared_path)
        shared_root = shared_tree.getroot()
        shared = [get_shared_text(si) for si in shared_root.findall(q("si"))]
        shared_index = {text: i for i, text in enumerate(shared)}

        def add_shared(text: str) -> int:
            if text in shared_index:
                return shared_index[text]
            idx = len(shared)
            shared.append(text)
            shared_index[text] = idx
            shared_root.append(make_si(text))
            return idx

        sheet_tree = ET.parse(sheet_path)
        sheet_root = sheet_tree.getroot()
        cells = {cell.get("r"): cell for cell in sheet_root.iter(q("c")) if cell.get("r")}

        touched = 0
        for row in range(5, 205):
            num = int(float(text_from_cell(cells.get(f"A{row}"), shared) or 0))
            if not 1 <= num <= 200:
                continue
            category = text_from_cell(cells.get(f"B{row}"), shared)
            title = text_from_cell(cells.get(f"C{row}"), shared)
            ingredients = text_from_cell(cells.get(f"F{row}"), shared)
            description = text_from_cell(cells.get(f"G{row}"), shared)
            updates = apply_replacements(num, title, ingredients, description, category)
            if num in OVERRIDES:
                updates.update(OVERRIDES[num])
            for col, value in updates.items():
                ref = f"{col}{row}"
                if ref in cells and text_from_cell(cells[ref], shared) != value:
                    set_text(cells[ref], value, add_shared)
                    touched += 1
            clear_cell(cells.get(f"J{row}"))

        shared_root.set("count", str(len(shared)))
        shared_root.set("uniqueCount", str(len(shared)))
        shared_tree.write(shared_path, encoding="utf-8", xml_declaration=True)
        sheet_tree.write(sheet_path, encoding="utf-8", xml_declaration=True)

        temp_output = OUTPUT.with_suffix(".tmp.xlsx")
        if temp_output.exists():
            temp_output.unlink()
        with zipfile.ZipFile(temp_output, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in tmp.rglob("*"):
                if path.is_file():
                    zf.write(path, path.relative_to(tmp).as_posix())
        temp_output.replace(OUTPUT)
        print(f"Applied editorial updates: {touched}")
        print(f"Saved: {OUTPUT}")


