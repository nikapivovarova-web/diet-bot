NS_MAIN = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
NS_XML = "http://www.w3.org/XML/1998/namespace"
ET.register_namespace("", NS_MAIN)


def q(tag: str) -> str:
    return f"{{{NS_MAIN}}}{tag}"


def get_shared_text(si: ET.Element) -> str:
    return "".join(t.text or "" for t in si.iter(q("t")))


def make_si(text: str) -> ET.Element:
    si = ET.Element(q("si"))
    t = ET.SubElement(si, q("t"))
    if text.startswith((" ", "\n")) or text.endswith((" ", "\n")) or "\n" in text:
        t.set(f"{{{NS_XML}}}space", "preserve")
    t.text = text
    return si


def text_from_cell(cell: ET.Element | None, shared: list[str]) -> str:
    if cell is None:
        return ""
    v = cell.find(q("v"))
    if v is None or v.text is None:
        return ""
    if cell.get("t") == "s":
        return shared[int(v.text)]
    return v.text


def set_text(cell: ET.Element, text: str, add_shared) -> None:
    cell.set("t", "s")
    v = cell.find(q("v"))
    if v is None:
        v = ET.SubElement(cell, q("v"))
    v.text = str(add_shared(text))


def clear_cell(cell: ET.Element | None) -> None:
    if cell is None:
        return
    cell.attrib.pop("t", None)
    v = cell.find(q("v"))
    if v is not None:
        cell.remove(v)


